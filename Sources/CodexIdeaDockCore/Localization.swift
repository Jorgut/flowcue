import Foundation

public enum AppLanguage: String, CaseIterable, Sendable {
    case english = "en"
    case mandarin = "zh-Hans"

    public var displayName: String {
        switch self {
        case .english: "English"
        case .mandarin: "简体中文"
        }
    }
}

