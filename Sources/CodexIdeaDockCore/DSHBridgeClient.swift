import Foundation

/// One pending DSH approval as exposed by the FlowCue DSH host plugin.
public struct DSHRemoteApproval: Codable, Identifiable, Hashable, Sendable {
    public let id: String
    public let toolName: String?
    public let callId: String?
    public let reason: String?
    public let displayReason: String?
    public let createdAt: String?

    public init(
        id: String,
        toolName: String? = nil,
        callId: String? = nil,
        reason: String? = nil,
        displayReason: String? = nil,
        createdAt: String? = nil
    ) {
        self.id = id
        self.toolName = toolName
        self.callId = callId
        self.reason = reason
        self.displayReason = displayReason
        self.createdAt = createdAt
    }

    public var title: String {
        displayReason ?? reason ?? toolName ?? "DSH approval"
    }
}

/// Decision payload sent back to the DSH bridge.
public struct DSHRemoteDecision: Codable, Sendable {
    public let id: String
    public let decision: String

    public init(id: String, decision: String) {
        self.id = id
        self.decision = decision
    }
}

/// Reads the token generated by `Integrations/DSHBridge` and talks to its
/// loopback-only HTTP API. The bridge is optional: when it is not installed,
/// FlowCue behaves exactly as before.
public final class DSHBridgeClient: @unchecked Sendable {
    public struct Configuration: Sendable {
        public var stateURL: URL
        public var baseURL: URL
        public var session: URLSession

        public init(
            stateURL: URL = DSHBridgeClient.defaultStateURL,
            baseURL: URL = DSHBridgeClient.defaultBaseURL,
            session: URLSession = .shared
        ) {
            self.stateURL = stateURL
            self.baseURL = baseURL
            self.session = session
        }
    }

    public static let defaultStateURL = URL(fileURLWithPath: NSHomeDirectory())
        .appendingPathComponent(".flowcue/dsh-bridge.json")
    public static let defaultBaseURL = URL(string: "http://127.0.0.1:47823")!

    private struct StateFile: Decodable {
        let token: String
        let port: Int?
    }

    private let configuration: Configuration

    public init(configuration: Configuration = Configuration()) {
        self.configuration = configuration
    }

    public var isConfigured: Bool {
        (try? token()) != nil
    }

    public func pending() async throws -> [DSHRemoteApproval] {
        let data = try await get(path: "/v1/pending")
        struct Response: Decodable { let pending: [DSHRemoteApproval] }
        return try JSONDecoder().decode(Response.self, from: data).pending
    }

    public func send(sessionID: String, text: String) async throws {
        var request = try authorizedRequest(path: "/v1/message", method: "POST")
        request.httpBody = try JSONEncoder().encode(DSHRemoteMessage(sessionId: sessionID, text: text))
        let (_, response) = try await configuration.session.data(for: request)
        try validate(response)
    }

    public func decide(id: String, decision: String) async throws {
        guard decision == "allowed-once" || decision == "rejected" else {
            throw DSHBridgeError.invalidDecision
        }
        var request = try authorizedRequest(path: "/v1/decide", method: "POST")
        request.httpBody = try JSONEncoder().encode(DSHRemoteDecision(id: id, decision: decision))
        let (_, response) = try await configuration.session.data(for: request)
        try validate(response)
    }

    private func get(path: String) async throws -> Data {
        let request = try authorizedRequest(path: path, method: "GET")
        let (data, response) = try await configuration.session.data(for: request)
        try validate(response)
        return data
    }

    private func authorizedRequest(path: String, method: String) throws -> URLRequest {
        var request = URLRequest(url: configuration.baseURL.appendingPathComponent(path))
        request.httpMethod = method
        request.timeoutInterval = 8
        request.setValue("Bearer \(try token())", forHTTPHeaderField: "Authorization")
        request.setValue("application/json", forHTTPHeaderField: "Accept")
        if method == "POST" {
            request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        }
        return request
    }

    private func token() throws -> String {
        guard let data = try? Data(contentsOf: configuration.stateURL),
              let state = try? JSONDecoder().decode(StateFile.self, from: data),
              state.token.count >= 24 else {
            throw DSHBridgeError.notInstalled
        }
        return state.token
    }

    private func validate(_ response: URLResponse) throws {
        guard let http = response as? HTTPURLResponse else { throw DSHBridgeError.invalidResponse }
        switch http.statusCode {
        case 200...299: return
        case 401: throw DSHBridgeError.unauthorized
        case 404: throw DSHBridgeError.requestExpired
        default: throw DSHBridgeError.httpStatus(http.statusCode)
        }
    }
}

public enum DSHBridgeError: LocalizedError, Equatable {
    case notInstalled
    case unauthorized
    case requestExpired
    case invalidDecision
    case invalidResponse
    case httpStatus(Int)

    public var errorDescription: String? {
        switch self {
        case .notInstalled: "DSH bridge plugin is not installed on the Mac."
        case .unauthorized: "DSH bridge token was rejected."
        case .requestExpired: "That DSH approval is no longer pending."
        case .invalidDecision: "Invalid DSH approval decision."
        case .invalidResponse: "The DSH bridge returned an invalid response."
        case .httpStatus(let code): "The DSH bridge returned HTTP \(code)."
        }
    }
}
