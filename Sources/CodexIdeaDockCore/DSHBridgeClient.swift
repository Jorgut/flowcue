import Foundation

/// One pending DSH approval as exposed by the FlowCue DSH host plugin.
public struct DSHRemoteApproval: Codable, Identifiable, Hashable, Sendable {
    public let id: String
    public let sessionId: String?
    public let toolName: String?
    public let callId: String?
    public let reason: String?
    public let displayReason: String?
    public let createdAt: String?
    public let agentID: String?

    public init(
        id: String,
        sessionId: String? = nil,
        toolName: String? = nil,
        callId: String? = nil,
        reason: String? = nil,
        displayReason: String? = nil,
        createdAt: String? = nil,
        agentID: String? = nil
    ) {
        self.id = id
        self.sessionId = sessionId
        self.toolName = toolName
        self.callId = callId
        self.reason = reason
        self.displayReason = displayReason
        self.createdAt = createdAt
        self.agentID = agentID
    }

    private enum CodingKeys: String, CodingKey {
        case id, sessionId, toolName, callId, reason, displayReason, createdAt, agentID
    }

    /// Auto review 会把原因写成多语言对象；旧版是字符串。两种都要能解。
    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decode(String.self, forKey: .id)
        sessionId = try? container.decode(String.self, forKey: .sessionId)
        toolName = try? container.decode(String.self, forKey: .toolName)
        callId = try? container.decode(String.self, forKey: .callId)
        createdAt = try? container.decode(String.self, forKey: .createdAt)
        agentID = try container.decodeIfPresent(String.self, forKey: .agentID)
        reason = Self.text(from: container, forKey: .reason)
        displayReason = Self.text(from: container, forKey: .displayReason)
    }

    private static func text(from container: KeyedDecodingContainer<CodingKeys>, forKey key: CodingKeys) -> String? {
        if let value = try? container.decode(String.self, forKey: key) {
            return value
        }
        if let localized = try? container.decode([String: String].self, forKey: key) {
            return localized["zh"] ?? localized["en"] ?? localized.values.first
        }
        return nil
    }

    public var title: String {
        displayReason ?? reason ?? toolName ?? "DSH approval"
    }
}

/// 一次提问（可能包含多个问题）。
public struct DSHRemoteQuestionBatch: Codable, Identifiable, Hashable, Sendable {
    public struct Question: Codable, Hashable, Sendable, Identifiable {
        public struct Option: Codable, Hashable, Sendable {
            public let label: String
            public let detail: String?

            public init(label: String, detail: String? = nil) {
                self.label = label
                self.detail = detail
            }
        }

        public let id: String
        public let title: String
        public let detail: String?
        public let multiSelect: Bool
        public let options: [Option]
    }

    public let id: String
    public let createdAt: String?
    /// 这个问题属于哪个 DSH 会话；手机据此把卡片放回对应 chat。
    public let sessionId: String?
    public let questions: [Question]
}

/// 回答某一次提问。
public struct DSHQuestionAnswer: Codable, Sendable {
    public struct Item: Codable, Sendable {
        public let id: String
        public let selected: [String]
        public let custom: String?

        public init(id: String, selected: [String], custom: String? = nil) {
            self.id = id
            self.selected = selected
            self.custom = custom
        }
    }

    public let id: String
    public let answers: [Item]
}

/// `GET /v1/dsh/approvals` 的响应，供手机端解码。
public struct DSHRemoteApprovalsResponse: Codable, Sendable {
    public let available: Bool
    public let pending: [DSHRemoteApproval]

    public init(available: Bool, pending: [DSHRemoteApproval]) {
        self.available = available
        self.pending = pending
    }
}

/// Decision payload sent back to the DSH bridge.
public struct DSHRemoteDecision: Codable, Sendable {
    public let id: String
    public let decision: String

    public init(id: String, decision: String) {
        self.id = id
        self.decision = decision
    }
}

/// Reads the token generated by `Integrations/DSHBridge` and talks to its
/// loopback-only HTTP API. The bridge is optional: when it is not installed,
/// FlowCue behaves exactly as before.
public final class DSHBridgeClient: @unchecked Sendable {
    public struct Configuration: Sendable {
        public var stateURL: URL
        public var baseURL: URL
        public var session: URLSession

        public init(
            stateURL: URL = DSHBridgeClient.defaultStateURL,
            baseURL: URL = DSHBridgeClient.defaultBaseURL,
            session: URLSession = .shared
        ) {
            self.stateURL = stateURL
            self.baseURL = baseURL
            self.session = session
        }
    }

    public static let defaultStateURL = URL(fileURLWithPath: NSHomeDirectory())
        .appendingPathComponent(".flowcue/dsh-bridge.json")
    public static let defaultBaseURL = URL(string: "http://127.0.0.1:47823")!

    private struct StateFile: Decodable {
        let token: String
        let port: Int?
    }

    private let configuration: Configuration

    public init(configuration: Configuration = Configuration()) {
        self.configuration = configuration
    }

    public var isConfigured: Bool {
        (try? token()) != nil
    }

    /// 读待审批列表。
    ///
    /// `source` 只有替手机转发时才传 `"phone"`：桥接拿它判断「手机在不在线」，
    /// 桌面自己的轮询（角标、待审批面板）不能冒充手机，否则每条审批都会被扣住
    /// 等手机，最后拖到 fallback 才出现在桌面上。
    public func pending(source: String? = nil) async throws -> [DSHRemoteApproval] {
        let query = source.map { [URLQueryItem(name: "source", value: $0)] } ?? []
        let data = try await get(path: "/v1/pending", query: query)
        struct Response: Decodable { let pending: [DSHRemoteApproval] }
        return try JSONDecoder().decode(Response.self, from: data).pending
    }

    public func send(sessionID: String, text: String, images: [String] = []) async throws {
        var request = try authorizedRequest(path: "/v1/message", method: "POST")
        request.httpBody = try JSONEncoder().encode(DSHRemoteMessage(sessionId: sessionID, text: text, images: images.isEmpty ? nil : images))
        let (_, response) = try await configuration.session.data(for: request)
        try validate(response)
    }

    /// 读待回答的问题（和审批同一个端点，只是取 questions 字段）。
    public func questions() async throws -> [DSHRemoteQuestionBatch] {
        let data = try await get(path: "/v1/pending")
        struct Response: Decodable { let questions: [DSHRemoteQuestionBatch]? }
        return try JSONDecoder().decode(Response.self, from: data).questions ?? []
    }

    public func answer(_ answer: DSHQuestionAnswer) async throws {
        var request = try authorizedRequest(path: "/v1/answer", method: "POST")
        request.httpBody = try JSONEncoder().encode(answer)
        let (_, response) = try await configuration.session.data(for: request)
        try validate(response)
    }

    public func decide(id: String, decision: String) async throws {
        guard decision == "allowed-once" || decision == "rejected" else {
            throw DSHBridgeError.invalidDecision
        }
        var request = try authorizedRequest(path: "/v1/decide", method: "POST")
        request.httpBody = try JSONEncoder().encode(DSHRemoteDecision(id: id, decision: decision))
        let (_, response) = try await configuration.session.data(for: request)
        try validate(response)
    }

    private func get(path: String, query: [URLQueryItem] = []) async throws -> Data {
        let request = try authorizedRequest(path: path, method: "GET", query: query)
        let (data, response) = try await configuration.session.data(for: request)
        try validate(response)
        return data
    }

    private func authorizedRequest(
        path: String,
        method: String,
        query: [URLQueryItem] = []
    ) throws -> URLRequest {
        let base = configuration.baseURL.appendingPathComponent(path)
        var components = URLComponents(url: base, resolvingAgainstBaseURL: false)
        if !query.isEmpty { components?.queryItems = query }
        guard let url = components?.url else { throw DSHBridgeError.invalidResponse }
        var request = URLRequest(url: url)
        request.httpMethod = method
        request.timeoutInterval = 8
        request.setValue("Bearer \(try token())", forHTTPHeaderField: "Authorization")
        request.setValue("application/json", forHTTPHeaderField: "Accept")
        if method == "POST" {
            request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        }
        return request
    }

    private func token() throws -> String {
        guard let data = try? Data(contentsOf: configuration.stateURL),
              let state = try? JSONDecoder().decode(StateFile.self, from: data),
              state.token.count >= 24 else {
            throw DSHBridgeError.notInstalled
        }
        return state.token
    }

    private func validate(_ response: URLResponse) throws {
        guard let http = response as? HTTPURLResponse else { throw DSHBridgeError.invalidResponse }
        switch http.statusCode {
        case 200...299: return
        case 401: throw DSHBridgeError.unauthorized
        case 404: throw DSHBridgeError.requestExpired
        default: throw DSHBridgeError.httpStatus(http.statusCode)
        }
    }
}

public enum DSHBridgeError: LocalizedError, Equatable {
    case notInstalled
    case unauthorized
    case requestExpired
    case invalidDecision
    case invalidResponse
    case httpStatus(Int)

    public var errorDescription: String? {
        switch self {
        case .notInstalled: "DSH bridge plugin is not installed on the Mac."
        case .unauthorized: "DSH bridge token was rejected."
        case .requestExpired: "That DSH approval is no longer pending."
        case .invalidDecision: "Invalid DSH approval decision."
        case .invalidResponse: "The DSH bridge returned an invalid response."
        case .httpStatus(let code): "The DSH bridge returned HTTP \(code)."
        }
    }
}
